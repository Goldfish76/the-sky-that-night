const CN_DIGITS = ['〇', '一', '二', '三', '四', '五', '六', '七', '八', '九'];

function cnNumber(n) {
  if (n <= 10) return n === 10 ? '十' : CN_DIGITS[n];
  if (n < 20) return '十' + CN_DIGITS[n - 10];
  const tens = Math.floor(n / 10), ones = n % 10;
  return CN_DIGITS[tens] + '十' + (ones ? CN_DIGITS[ones] : '');
}

const SHICHEN = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];

export function shichen(hour) {
  return SHICHEN[Math.floor(((hour + 1) % 24) / 2)] + '时';
}

export function cnNumeralDate({ y, m, d }) {
  const year = String(y).split('').map(ch => CN_DIGITS[+ch]).join('');
  return `${year}年${cnNumber(m)}月${cnNumber(d)}日`;
}

const LUNAR_DAYS = [
  '初一', '初二', '初三', '初四', '初五', '初六', '初七', '初八', '初九', '初十',
  '十一', '十二', '十三', '十四', '十五', '十六', '十七', '十八', '十九', '二十',
  '廿一', '廿二', '廿三', '廿四', '廿五', '廿六', '廿七', '廿八', '廿九', '三十',
];

// Chinese lunisolar date, e.g. "丙午年八月廿四", from the browser's built-in Chinese calendar.
export function lunarDate({ y, m, d }) {
  try {
    const fmt = new Intl.DateTimeFormat('zh-CN-u-ca-chinese', {
      timeZone: 'UTC', year: 'numeric', month: 'long', day: 'numeric',
    });
    const parts = fmt.formatToParts(new Date(Date.UTC(y, m - 1, d, 12)));
    const get = type => (parts.find(p => p.type === type) || {}).value || '';
    const yearName = get('yearName');
    const month = get('month');
    const dayNum = parseInt(get('day'), 10);
    const day = Number.isFinite(dayNum) ? LUNAR_DAYS[dayNum - 1] : get('day');
    if (!yearName || !month || !day) return '';
    return `${yearName}年${month}${day}`;
  } catch {
    return '';
  }
}

const pad = n => String(n).padStart(2, '0');

export function formatDateLine(lang, local, style) {
  const { y, m, d, hh, mm } = local;
  if (lang === 'zh') {
    if (style === 'ink') return `${cnNumeralDate(local)} · ${shichen(hh)}`;
    return `${y}年${m}月${d}日 ${pad(hh)}:${pad(mm)}`;
  }
  const date = new Date(Date.UTC(y, m - 1, d, 12));
  const dateStr = new Intl.DateTimeFormat('en-US', { timeZone: 'UTC', year: 'numeric', month: 'long', day: 'numeric' }).format(date);
  const h12 = ((hh + 11) % 12) + 1;
  const ampm = hh < 12 ? 'AM' : 'PM';
  return `${dateStr} · ${h12}:${pad(mm)} ${ampm}`;
}

export function formatCoords(lang, lat, lon) {
  const la = Math.abs(lat).toFixed(2), lo = Math.abs(lon).toFixed(2);
  if (lang === 'zh') {
    return `${lat >= 0 ? '北纬' : '南纬'} ${la}° · ${lon >= 0 ? '东经' : '西经'} ${lo}°`;
  }
  return `${la}° ${lat >= 0 ? 'N' : 'S'} · ${lo}° ${lon >= 0 ? 'E' : 'W'}`;
}

// Named phase from the Moon's ecliptic elongation (0 = new, 180 = full) and illuminated fraction.
export function moonPhaseName(lang, phaseDeg, fraction) {
  const p = ((phaseDeg % 360) + 360) % 360;
  let idx;
  if (fraction < 0.03) idx = 0;
  else if (fraction > 0.97) idx = 4;
  else if (Math.abs(p - 90) < 10) idx = 2;
  else if (Math.abs(p - 270) < 10) idx = 6;
  else if (p < 180) idx = fraction < 0.5 ? 1 : 3;
  else idx = fraction < 0.5 ? 7 : 5;
  return STR[lang].moonPhases[idx];
}
