export function cityLabel(c, lang) {
  return lang === 'zh' ? `${c[1]} · ${c[0]}` : `${c[0]} · ${c[1]}`;
}

export function findCity(text) {
  const t = (text || '').trim().toLowerCase();
  if (!t) return null;
  return CITIES.find(c =>
    cityLabel(c, 'zh').toLowerCase() === t || cityLabel(c, 'en').toLowerCase() === t ||
    c[0].toLowerCase() === t || c[1] === t
  ) || CITIES.find(c => c[0].toLowerCase().startsWith(t) || c[1].startsWith(t)) || null;
}
